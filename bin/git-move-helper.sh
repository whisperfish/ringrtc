set -eo pipefail

# shellcheck source=bin/env.sh
. "$(dirname "$0")"/env.sh

# env.sh may not be able to handle this, but add it here
set -u

usage()
{
    echo "usage: $0 full/webrtc/checkout/path"
    echo
    echo "    $0 copies all files from src/ringrtc/rffi/api/ in the specified"
    echo "    webrtc checkout to ${RINGRTC_SRC_DIR}/rust/src/webrtc_include,"
    echo "    maintaining the contents and git history, while also adding a"
    echo "    reference to the original commit hash"
    echo
    echo "    NOTE: The specified webrtc checkout must **NOT** be a shallow "
    echo "    clone, which ${WEBRTC_SRC_DIR} typically is"
    echo
    echo "    Exits with a non-zero status if any of the source files do not exist"
    echo "    or if any of the files that would be created DO exist."
    echo
    echo "    $0 will *NOT* delete or otherwise modify the files in webrtc."
    exit 1
}

if [ "$#" -ne 1 ]; then
  usage
fi

WEBRTC_PATH="$1"

if [ "$(git -C "${WEBRTC_PATH}" rev-parse --is-shallow-repository)" = "true" ]; then
  echo "fatal: ${WEBRTC_PATH} is a shallow checkout and will not have full history"
  usage
fi

SOURCE_DIR="ringrtc/rffi/api"

# Similar to "pretty.email", but with the addition of the original commit
# hash in the commit message section, so that git am adds a reference
# back to the original commit.
#
# Full documentation is available at https://git-scm.com/docs/pretty-formats

# * %H: commit hash
# The specific date seems to appear in all commit summaries as generated by
# --pretty=email, and it appears to be load-bearing - likely it is the date of
# the "email"?
COMMIT_LINE='From %H Mon Sep 17 00:00:00 2001'
# * %an: author name
# * %ae: author email
AUTHOR_LINE='From: %an <%ae>'
# * %aD: author date, RFC2822 style
DATE_LINE='Date: %aD'
# * %s: subject
SUBJECT_LINE='Subject: [PATCH] %s'
# * %b: "body"
# * "%-b" means "body, but removing any consecutive newlines before it if it
#   is empty
BODY_LINE='%-b'
ORIGINAL_COMMIT_LINE='Copied from signalapp/webrtc commit %H'
# * %n: newline
GIT_FORMAT_STR="${COMMIT_LINE}%n${AUTHOR_LINE}%n${DATE_LINE}%n${SUBJECT_LINE}%n%n${BODY_LINE}%n%n${ORIGINAL_COMMIT_LINE}%n"

TMPFILE="$(mktemp temp.patch.XXXXXX)"
echo "Writing to ${TMPFILE}"

git -C "${WEBRTC_PATH}" log --patch-with-stat --reverse --full-index\
  --binary -m --first-parent --relative="${SOURCE_DIR}" \
  --pretty="format:${GIT_FORMAT_STR}" -- "${SOURCE_DIR}" > "${TMPFILE}"

# whitespace=nowarn: Allow trailing whitespace; just keep the commits as-is
git -C "${RINGRTC_SRC_DIR}" am --directory=src/rust/src/webrtc_include \
  --committer-date-is-author-date \
  --whitespace=nowarn  "../${TMPFILE}"
